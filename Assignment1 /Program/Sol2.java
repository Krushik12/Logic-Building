// Write a Java program that checks if a predefined number is negative using an if-else statement and displays the result.
class Sol2 {
    public static void main(String[] args) {
        int number = -10;

        if (number < 0) {
            System.out.println("The number is negative.");
        } else {
            System.out.println("The number is not negative.");
        }
    }
}